"""Generate the weapon catalogue from an installed game's data files (read-only)."""
import argparse
import hashlib
import json
import re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--data", type=Path, required=True)
parser.add_argument("--sdk", type=Path, default=Path("D:/plugin-sdk"))
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
ids = {name: int(value, 16) for name, value in re.findall(r"WEAPONTYPE_(\w+)\s*=\s*(0x[0-9A-Fa-f]+)", (args.sdk / "plugin_sa/game_sa/enums/eWeaponType.h").read_text())}
config = args.data / "gtasa_weapon_config.dat"
if config.exists():
    for line in config.read_text(encoding="cp1252").splitlines():
        fields = line.split()
        if len(fields) > 1 and fields[0].isdigit() and fields[1] in ids:
            if ids[fields[1]] != int(fields[0]):
                raise ValueError("Weapon ID differs from Plugin-SDK: " + fields[1])
models = {}
for line in (args.data / "default.ide").read_text(encoding="cp1252").splitlines():
    fields = [part.strip() for part in line.split(",")]
    if len(fields) > 1 and fields[0].isdigit():
        models[int(fields[0])] = fields[1]
rows = {}
for line in (args.data / "weapon.dat").read_text(encoding="cp1252").splitlines():
    fields = line.split()
    if fields and fields[0] in ("$", "£"):
        _, name, fire, _, _, first, second, slot, *_ = fields
        row = (fire, int(first), int(second), int(slot))
        if name in rows and rows[name] != row:
            raise ValueError("Skill-dependent model/type/slot mapping: " + name)
        rows[name] = row
names = "Unarmed BrassKnuckles GolfClub Nightstick Knife BaseballBat Shovel PoolCue Katana Chainsaw Dildo1 Dildo2 Vibrator1 Vibrator2 Flowers Cane Grenade TearGas Molotov Rocket HeatSeekingRocket FreefallBomb Pistol SilencedPistol DesertEagle Shotgun SawedOffShotgun CombatShotgun MicroUzi Mp5 Ak47 M4 Tec9 CountryRifle SniperRifle RocketLauncher HeatSeekingRocketLauncher Flamethrower Minigun SatchelCharge Detonator SprayCan FireExtinguisher Camera NightVision Infrared Parachute".split()
fire_names = dict(MELEE="Melee", INSTANT_HIT="InstantHit", PROJECTILE="Projectile", AREA_EFFECT="AreaEffect", CAMERA="Camera", USE="Use")
entries = []
enums = []
for name, (fire, first, second, slot) in sorted(rows.items(), key=lambda item: ids[item[0]]):
    number = ids[name]
    friendly = names[number]
    enums.append(f"    {friendly} = {number},")
    for model in (first, second):
        if model >= 0 and model not in models:
            raise ValueError(f"Model {model} absent from default.ide")
    def literal(model):
        return json.dumps(models[model]) if model >= 0 else "null"
    entries.append(f'        new(WeaponType.{friendly}, "{name}", WeaponFireType.{fire_names[fire]}, {first}, {second}, {slot}, {literal(first)}, {literal(second)}),')
output = "// Generated by tools/generate_weapons.py from weapon.dat, default.ide and Plugin-SDK.\nnamespace SharpAndreas;\n\npublic enum WeaponType\n{\n" + "\n".join(enums) + "\n}\n\npublic sealed partial class WeaponInfo\n{\n    private static readonly WeaponInfo[] entries =\n    [\n" + "\n".join(entries) + "\n    ];\n}\n"
(root / "managed/SharpAndreas.Api/WeaponInfo.Data.g.cs").write_text(output)
source_files = ["weapon.dat", "default.ide"] + (["gtasa_weapon_config.dat"] if config.exists() else [])
report = {
    "data_directory": str(args.data),
    "weapon_count": len(entries),
    "referenced_model_count": len(set(model for row in rows.values() for model in row[1:3] if model >= 0)),
    "source_files": {name: hashlib.sha256((args.data / name).read_bytes()).hexdigest() for name in source_files},
    "notes": ["Read-only scan; no game files modified.", "Weapon IDs validated against Plugin-SDK and the installed limit-adjuster configuration when present.", "Reverse model lookup includes shared and secondary models.", "Unarmed has no model (-1).", "Skill variants agree on fire type, models and slot."]
}
(root / "WEAPON-DATA-SCAN.json").write_text(json.dumps(report, indent=2) + "\n")
print(f"Generated {len(entries)} weapons; {len(set(m for row in rows.values() for m in row[1:3] if m >= 0))} referenced models.")
