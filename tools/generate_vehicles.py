"""Generate vehicle metadata from an installed game's data directory (read-only)."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--data', type=Path, required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
kinds = dict(car='Automobile', mtruck='MonsterTruck', quad='Quad', heli='Helicopter', plane='Plane', boat='Boat', train='Train', bike='Motorcycle', bmx='Bicycle', trailer='Trailer')
classes = dict(normal='Normal', poorfamily='PoorFamily', richfamily='RichFamily', executive='Executive', worker='Worker', big='Big', taxi='Taxi', moped='Moped', motorbike='Motorbike', leisureboat='LeisureBoat', workerboat='WorkerBoat', bicycle='Bicycle', ignore='Ignore')
handling_ids = set()
for line in (args.data / 'handling.cfg').read_text(encoding='cp1252').splitlines():
    fields = line.split(';')[0].split()
    if fields and fields[0][0].isalnum():
        handling_ids.add(fields[0])
entries = []
seen = set()
for line in (args.data / 'vehicles.ide').read_text(encoding='cp1252').splitlines():
    fields = line.split('#')[0].replace(',', ' ').split()
    if not fields or not fields[0].isdigit():
        continue
    if len(fields) not in (11,15):
        raise ValueError('Unexpected vehicle fields: ' + line)
    model, name, txd, kind, handling, game_name, animation, category, frequency, flags, components = fields[:11]
    number = int(model)
    if number in seen:
        raise ValueError('Duplicate vehicle model: ' + model)
    seen.add(number)
    if handling not in handling_ids:
        raise ValueError('Missing handling profile: ' + handling)
    anim = 'null' if animation.lower() == 'null' else json.dumps(animation)
    if len(fields) == 15:
        wheel, front, rear, upgrade = fields[11:]
        extra = f'{int(wheel)}, {float(front)}f, {float(rear)}f, {int(upgrade)}'
    else:
        extra = 'null, null, null, null'
    entries.append(f'        new({number}, {json.dumps(name)}, {json.dumps(txd)}, VehicleKind.{kinds[kind]}, {json.dumps(handling)}, {json.dumps(game_name)}, {anim}, VehicleClass.{classes[category]}, {int(frequency)}, {int(flags,16)}u, 0x{int(components,16):X}u, {extra}),')
output = '// Generated by tools/generate_vehicles.py from vehicles.ide; handling references validated against handling.cfg.\nnamespace SharpAndreas;\n\npublic readonly partial record struct VehicleInfo\n{\n    private static readonly VehicleInfo[] entries =\n    [\n' + '\n'.join(entries) + '\n    ];\n}\n'
(root / 'managed/SharpAndreas.Api/VehicleInfo.Data.g.cs').write_text(output)
report = {'data_directory':str(args.data), 'vehicle_models':len(entries), 'source_sha256':{name:hashlib.sha256((args.data/name).read_bytes()).hexdigest() for name in ['vehicles.ide','handling.cfg']}, 'notes':['Read-only scan; only declared models included.','All handling IDs validated against handling.cfg.','Missing optional wheel fields are null, not invented defaults.','Flags and component rules parsed as hexadecimal.']}
(root / 'VEHICLE-DATA-SCAN.json').write_text(json.dumps(report,indent=2)+'\n')
print(f'Generated {len(entries)} vehicle models; every handling reference validated.')
