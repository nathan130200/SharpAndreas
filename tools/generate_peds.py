"""Generate ped model/stat metadata from an installed game's data directory (read-only)."""
import argparse
import hashlib
import json
import re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--data', type=Path, required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
stats = {}
stat_entries = []
quote = json.dumps
for line in (args.data / 'pedstats.dat').read_text(encoding='cp1252').splitlines():
    fields = line.split('#')[0].split()
    if not fields or not fields[0].startswith('STAT_'):
        continue
    if len(fields) != 11:
        raise ValueError('Unexpected pedstats row: ' + line)
    name, flee, heading, fear, temper, lawful, sexy, attack, defend, shooting, decision = fields
    index = len(stats)
    stats[name] = index
    stat_entries.append(f'        new({index}, {quote(name)}, {float(flee)}f, {float(heading)}f, {int(fear)}, {int(temper)}, {int(lawful)}, {int(sexy)}, {float(attack)}f, {float(defend)}f, {int(shooting)}, {int(decision)}),')
types = dict(zip('PLAYER1 PLAYER2 PLAYER_NETWORK PLAYER_UNUSED CIVMALE CIVFEMALE COP GANG1 GANG2 GANG3 GANG4 GANG5 GANG6 GANG7 GANG8 GANG9 GANG10 DEALER MEDIC FIREMAN CRIMINAL BUM PROSTITUTE SPECIAL MISSION1 MISSION2 MISSION3 MISSION4 MISSION5 MISSION6 MISSION7 MISSION8'.split(), 'Player1 Player2 NetworkPlayer UnusedPlayer CivilianMale CivilianFemale Cop Ballas Grove Vagos Rifa DaNangBoys Mafia Triads Forellis Sindaccos Gang10 Dealer Medic Fireman Criminal Bum Prostitute Special Mission1 Mission2 Mission3 Mission4 Mission5 Mission6 Mission7 Mission8'.split()))
peds = []
seen = set()
for line in (args.data / 'peds.ide').read_text(encoding='cp1252').splitlines():
    # The game's text format permits comma and whitespace separators (model 51 mixes them).
    fields = re.split(r'[,\s]+', line.split('#')[0].strip())
    if not fields or not fields[0].isdigit():
        continue
    if len(fields) != 14:
        raise ValueError('Unexpected ped row: ' + line)
    model, name, txd, kind, stat, animation, cars, flags, animfile, radio1, radio2, audio, voice_min, voice_max = fields
    number = int(model)
    if number in seen:
        raise ValueError('Duplicate ped model: ' + model)
    seen.add(number)
    anim = 'null' if animfile.lower() == 'null' else quote(animfile)
    peds.append(f'        new({number}, {quote(name)}, {quote(txd)}, PedType.{types[kind]}, stats[{stats[stat]}], {quote(animation)}, (PedVehiclePreferences)0x{int(cars,16):X}, {int(flags,16)}u, {anim}, {int(radio1)}, {int(radio2)}, {quote(audio)}, {quote(voice_min)}, {quote(voice_max)}),')
output = '// Generated by tools/generate_peds.py from peds.ide and pedstats.dat.\nnamespace SharpAndreas;\n\npublic readonly partial record struct PedInfo\n{\n    private static readonly PedStats[] stats =\n    [\n' + '\n'.join(stat_entries) + '\n    ];\n    private static readonly PedInfo[] entries =\n    [\n' + '\n'.join(peds) + '\n    ];\n}\n'
(root / 'managed/SharpAndreas.Api/PedInfo.Data.g.cs').write_text(output)
report = {'data_directory':str(args.data), 'ped_models':len(peds), 'stats_profiles':len(stats), 'source_sha256':{name:hashlib.sha256((args.data/name).read_bytes()).hexdigest() for name in ['peds.ide','pedstats.dat']}, 'notes':['Read-only scan; only declared models included, model ID gaps preserved.','Special model slots preserve placeholder names; runtime replacements are not inferred.','Model 51 uses mixed comma/whitespace separators.']}
(root / 'PED-DATA-SCAN.json').write_text(json.dumps(report,indent=2)+'\n')
print(f'Generated {len(peds)} ped models and {len(stats)} stats profiles.')
